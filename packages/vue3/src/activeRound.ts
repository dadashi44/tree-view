import type { InjectionKey, Ref } from 'vue'

/**
 * Раунд, который сейчас виден в свайпере.
 *
 * Кладёт `BracketRounds`, читает `TreeView`: в свайпере виден один раунд,
 * и высоту холста надо держать по нему, а не по всей раскладке — иначе под
 * финалом с единственной ячейкой остаётся пустота во всю высоту сетки.
 *
 * `null` — свайпера нет (широкий экран или `TreeView` стоит сам по себе),
 * высота считается по всей раскладке, как и раньше.
 */
export const ACTIVE_ROUND: InjectionKey<Ref<number | null>> = Symbol('tv-active-round')
